"""Same controlled sweeps as kp_figs_data.py but with first-principles k.p parameters (Kormanyos et al. 2015, DFT, MoS2):
gamma=2.76 eV A, kappa=-1.48 eV A^2, Delta=1.67 eV, m_c=0.46, m_v=-0.54.  Units: k in 1/A.
w is the BARE diagonal curvature: w = (hbar^2/4m_e)(1/m_c + 1/|m_v|) - gamma^2/(2 m_D)  (the Dirac part of the band
masses is generated by the d-vector itself and must not be counted twice)."""
import os, sys, json, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); import kp2
MUB = 5.7883818060e-5; HB2M = 3.80998   # hbar^2/2m_e  eV A^2
D, g, kap, mc, mv = 1.67, 2.76, -1.48, 0.46, -0.54
mD = D/2; w = 0.5*HB2M*(1/mc + 1/abs(mv)) - g*g/(2*mD)
base = dict(v=g, kappa=kap, beta=w, mD=mD, lam=0.073)
print("Kormanyos MoS2: w_bare = %.3f eV A^2 (old code used %.3f, i.e. full masses)" % (w, 0.5*HB2M*(1/mc+1/abs(mv))))
R, NK, NU, BT = 0.2, 401, 0.005, 30.0; DEL = np.array([0.05, 0.10])
def chi(p):
    Eg = 2*p['mD']-p['lam']; om = Eg+DEL; b = MUB*BT
    ep = kp2.response('x', b, om, p=p, R=R, Nk=NK, nu=NU, want_shift=False)[0]
    em = kp2.response('x', -b, om, p=p, R=R, Nk=NK, nu=NU, want_shift=False)[0]
    return ((ep-em)/(2*BT)).tolist()
sw = {}
grids = {'kappa': np.linspace(-2.0, 2.0, 21), 'v': g*np.linspace(0.5, 1.5, 21),
         'mD': np.linspace(0.5, 1.1, 21), 'lam': np.linspace(0.0, 0.25, 21)}
for name, gr in grids.items():
    vals = []
    for x in gr:
        p = dict(base); p[name] = float(x); vals.append(chi(p))
    sw[name] = dict(x=gr.tolist(), chi=vals); print(name, "done", flush=True)
sw['base'] = base; sw['units'] = "k in 1/A; chi in code units (Angstrom-based)"
json.dump(sw, open(os.path.join(HERE, "kp_sweeps_korm.json"), "w"), indent=1)
